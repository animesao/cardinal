func TestNewRoot_CompletionSubcommandExists(t *testing.T) {
	root := NewRoot()
	// `completion` is generated by cobra when the root command is
	// either executed once or has InitDefaultCompletionCmd() called.
	// Tests that only inspect the tree may not have triggered that
	// lazy registration yet, so we call it explicitly here.
	root.InitDefaultCompletionCmd()
	var ok bool
	for _, sub := range root.Commands() {
		if sub.Name() == "completion" {
			ok = true
		}
	}
	if !ok {
		t.Errorf("cobra root is missing `completion` subcommand (need cobra v1.1+)")
	}
}

// TestRunCommand_DisablesFlagParsing is a regression guard. The `run`
// command sets DisableFlagParsing because every run-level flag (--rm,
// --network, --memory, --cap-add, etc.) is parsed by the legacy
// stdlib flag.NewFlagSet inside Run() rather than by cobra itself.
// Without DisableFlagParsing, cobra would reject every run invocation
// with `unknown flag: --rm`. If you migrate run-level flags into cobra,
// flip this assertion.
func TestRunCommand_DisablesFlagParsing(t *testing.T) {
	root := NewRoot()
	run := findRootSub(root, "run")
	if run == nil {
		t.Fatal("run command missing")
	}
	if !run.DisableFlagParsing {
		t.Errorf("run.DisableFlagParsing = false; want true (legacy flag parsing)")
	}
}

func TestLegacyFlagCommands_LongHelpDoesNotExit(t *testing.T) {
	for _, name := range []string{"run", "serve"} {
		name := name
		t.Run(name, func(t *testing.T) {
			stream := &bytes.Buffer{}
			root := NewRoot()
			root.SetArgs([]string{name, "--help"})
			root.SetOut(stream)
			root.SetErr(stream)

			if err := root.Execute(); err != nil {
				t.Fatalf("%s --help returned an error: %v", name, err)
			}
			if !strings.Contains(stream.String(), name) {
				t.Fatalf("%s --help did not include the command name: %q", name, stream.String())
			}
		})
	}
}

