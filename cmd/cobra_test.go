// findRootSub returns the first sub-command with the given name, or nil
// if absent. It mirrors cobra's own root.Commands iterator without
// requiring the caller to inspect Children/Aliases by hand.
func findRootSub(root *cobra.Command, name string) *cobra.Command {
	for _, c := range root.Commands() {
		if c.Name() == name {
			return c
		}
	}
	return nil
}
