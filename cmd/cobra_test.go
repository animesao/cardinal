// captureRun executes an isolated cobra command tree with the given args
// and returns the (possibly partial) stdout output. Errors are intentionally
// not asserted here — these tests assert structural properties of the tree,
// not user-facing behaviour.
func captureRun(t *testing.T, args []string) string {
	t.Helper()
	buf := &bytes.Buffer{}
	root := NewRoot()
	root.SetOut(buf)
	root.SetErr(buf)
	root.SetArgs(args)
	// Use a fresh log.Default pointer so logger config persists between
	// tests (but does not leak into the global package default).
	_ = io.Discard
	if err := root.Execute(); err != nil {
		// Most commands will exit non-zero when missing args. We only
		// want to test the help/usage path, so swallow the error.
		_ = err
	}
	return buf.String()
}

